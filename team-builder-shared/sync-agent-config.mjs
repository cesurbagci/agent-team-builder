function tomlString(value) {
  return JSON.stringify(value ?? '')
}

function tomlArray(values) {
  return `[${(values ?? []).map(tomlString).join(', ')}]`
}

// ---------------------------------------------------------------------------
// Generator context — collects writes/mismatches; performs side effects in
// sync mode only. In --check mode nothing is written/removed/created.
// ---------------------------------------------------------------------------

function createContext({ root, checkOnly }) {
  const resolvedRoot = path.resolve(root)
  const sourceRoot = path.join(resolvedRoot, '.agent-source')

  const mismatches = []
  const writes = []
  // Every generated path this run produced — whether it changed on disk or not.
  const produced = new Set()
  // Local output (localOutputPaths) is not in git: in CI and on a fresh clone
  // it is simply absent. --check reports an absent one as "not generated yet",
  // never as drift; one that is present but different still is drift.
  const localPaths = new Set()
  const notGenerated = []
  // Every model and effort this run resolved, for the catalog check.
  const resolvedModels = []

  const toPosix = filePath =>
    path.relative(resolvedRoot, filePath).split(path.sep).join('/')

  const resolveRoot = (...segments) => path.join(resolvedRoot, ...segments)
  const resolveSource = (...segments) => path.join(sourceRoot, ...segments)

  async function writeExpected(filePath, expected, { track = true, keepLineEndings = false } = {}) {
    const relative = toPosix(filePath)
    if (track) {
      produced.add(relative)
    }
    const normalizedExpected = normalizeText(expected)
    const exists = await pathExists(filePath)
    const actual = exists ? normalizeText(await readText(filePath)) : null

    if (actual === normalizedExpected) {
      return
    }
    if (checkOnly) {
      if (!exists && localPaths.has(relative)) {
        notGenerated.push(relative)
        return
      }
      mismatches.push(relative)
      return
    }
    await fs.mkdir(path.dirname(filePath), { recursive: true })
    await fs.writeFile(filePath, keepLineEndings ? expected : normalizedExpected)
    writes.push(toPosix(filePath))
  }

  async function copyExpected(sourcePath, targetPath, transform = text => text) {
    const source = await readText(sourcePath)
    await writeExpected(targetPath, transform(source))
  }

  return {
    resolvedRoot,
    sourceRoot,
    checkOnly,
    mismatches,
    writes,
    produced,
    localPaths,
    notGenerated,
    resolvedModels,
    toPosix,
    resolveRoot,
    resolveSource,
    writeExpected,
    copyExpected,
  }
}

